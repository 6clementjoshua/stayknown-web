function deliveryHealth(projection: DeliveryProjection): LiveDeliveryHealth {
  if (projection.notificationRecorded && projection.pushDelivered) {
    return "healthy";
  }

  if (projection.notificationRecorded || projection.pushDelivered) {
    return "degraded";
  }

  return "offline";
}

