function safeAbsoluteAvatarUrl(raw: string): string {
  if (!raw) return "";

  try {
    const url = new URL(raw);

    if (url.protocol !== "https:") return "";

    const allowedOrigin = configuredStorageOrigin();

    if (allowedOrigin && url.origin !== allowedOrigin) {
      return "";
    }

    return url.toString();
  } catch {
    return "";
  }
}

