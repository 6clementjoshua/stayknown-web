function opportunityId(params: {
  visitId: string;
  recipientContactId: string;
  deadlineVersion: number;
}): string {
  const secret = clean(
    process.env.LIVE_AUDIT_HASH_SECRET ??
      process.env.INTERNAL_EVENT_SECRET ??
      process.env.TRACKING_SIGNING_SECRET,
  );

  const material =
    `${params.visitId}:` +
    `${params.recipientContactId}:` +
    `${params.deadlineVersion}`;

  if (!secret) {
    return `visit-response-${params.deadlineVersion}`;
  }

  const digest = createHmac("sha256", secret)
    .update(`stayknown-live-response:${material}`, "utf8")
    .digest("base64url")
    .slice(0, 40);

  return `visit-response-${digest}`;
}

function safeEqualText(leftValue: string, rightValue: string): boolean {
  const left = Buffer.from(leftValue, "utf8");
  const right = Buffer.from(rightValue, "utf8");

  if (left.length !== right.length) return false;

  try {
    return timingSafeEqual(left, right);
  } catch {
    return false;
  }
}

function userAgentSummary(req: Request): JsonObject {
  const userAgent = clean(req.headers.get("user-agent")).slice(0, 1000);

  if (!userAgent) {
    return {
      available: false,
      raw_user_agent_stored: false,
    };
  }

  const normalized = userAgent.toLowerCase();

  const platform = normalized.includes("android")
    ? "android"
    : normalized.includes("iphone") ||
        normalized.includes("ipad") ||
        normalized.includes("ios")
      ? "ios"
      : normalized.includes("windows")
        ? "windows"
        : normalized.includes("macintosh") || normalized.includes("mac os")
          ? "macos"
          : normalized.includes("linux")
            ? "linux"
            : "unknown";

  const browser = normalized.includes("edg/")
    ? "edge"
    : normalized.includes("chrome/")
      ? "chrome"
      : normalized.includes("safari/") && !normalized.includes("chrome/")
        ? "safari"
        : normalized.includes("firefox/")
          ? "firefox"
          : "unknown";

  const secret = clean(
    process.env.LIVE_AUDIT_HASH_SECRET ??
      process.env.INTERNAL_EVENT_SECRET ??
      process.env.TRACKING_SIGNING_SECRET,
  );

  const userAgentHash = secret
    ? createHmac("sha256", secret)
        .update(`stayknown-live-response-client:${userAgent}`, "utf8")
        .digest("hex")
    : "";

  return {
    available: true,
    platform,
    browser,
    ...(userAgentHash ? { user_agent_hash: userAgentHash } : {}),
    raw_user_agent_stored: false,
  };
}

