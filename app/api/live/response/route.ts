function asObject(value: unknown): JsonObject {
  return value && typeof value === "object" && !Array.isArray(value)
    ? (value as JsonObject)
    : {};
}

function asStringArray(value: unknown): string[] {
  if (!Array.isArray(value)) return [];

  return Array.from(new Set(value.map((item) => clean(item)).filter(Boolean)));
}

function finiteInteger(value: unknown): number | null {
  if (typeof value === "number" && Number.isFinite(value)) {
    return Number.isSafeInteger(Math.trunc(value)) ? Math.trunc(value) : null;
  }

  const parsed = Number(clean(value));

  if (!Number.isFinite(parsed)) return null;

  const integer = Math.trunc(parsed);

  return Number.isSafeInteger(integer) ? integer : null;
}

function isUuid(value: unknown): boolean {
  return /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(
    clean(value),
  );
}

function dateMilliseconds(value: unknown): number | null {
  const raw = clean(value);

  if (!raw) return null;

  const date = new Date(raw);
  const milliseconds = date.getTime();

  return Number.isNaN(milliseconds) ? null : milliseconds;
}

