async function recordDeliveryHealth(
  admin: SupabaseClient,
  params: {
    ownerUserId: string;
    visitId: string;
    responderUserId: string;
    responseId: string;
    responseKind: LiveResponseAction;
    respondedAt: string;
    notificationRecorded: boolean;
    pushDelivered: boolean;
  },
): Promise<boolean> {
  const overallState =
    params.notificationRecorded && params.pushDelivered
      ? "delivered"
      : params.notificationRecorded || params.pushDelivered
        ? "partial"
        : "failed";

  try {
    const result = await admin.rpc("sk_upsert_safety_delivery_health", {
      p_owner_user_id: params.ownerUserId,
      p_flow_kind: "visit",
      p_related_id: params.visitId,
      p_source: "respond_visit_time_contact",
      p_health: {
        overall_state: overallState,
        delivery_confidence:
          overallState === "delivered"
            ? "high"
            : overallState === "partial"
              ? "medium"
              : "low",
        event: "visit_time_contact_response",
        response_id: params.responseId || null,
        response_kind: params.responseKind,
        responded_at: params.respondedAt,
        owner_notification_recorded: params.notificationRecorded,
        owner_push_delivered: params.pushDelivered,
        authority: {
          records_response: true,
          modifies_visit: false,
          changes_visit_deadline: false,
          ends_visit: false,
          starts_sos: false,
          contacts_emergency_services: false,
          proves_safety: false,
        },
      },
      p_viewer_user_ids: [params.ownerUserId, params.responderUserId],
    });

    if (result.error) {
      if (!backendObjectMissing(result.error)) {
        logDatabaseFailure("delivery-health projection", result.error);
      }

      return false;
    }

    return true;
  } catch (error) {
    if (!backendObjectMissing(error)) {
      logDatabaseFailure("delivery-health projection", error);
    }

    return false;
  }
}

