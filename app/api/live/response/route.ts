function backendObjectMissing(error: unknown): boolean {
  const row = asObject(error);
  const code = clean(row.code).toUpperCase();
  const message = [
    clean(row.message),
    clean(row.details),
    clean(row.hint),
    error instanceof Error ? error.message : "",
  ]
    .join(" ")
    .toLowerCase();

  return (
    code === "42P01" ||
    code === "42703" ||
    code === "42883" ||
    code === "PGRST202" ||
    code === "PGRST204" ||
    code === "PGRST205" ||
    message.includes("does not exist") ||
    message.includes("could not find the table") ||
    message.includes("could not find the function") ||
    message.includes("schema cache")
  );
}

async function signedAvatar(
  admin: SupabaseClient,
  rawPath: string,
): Promise<string> {
  const raw = clean(rawPath);

  if (!raw) return "";

  if (/^https?:\/\//i.test(raw)) {
    return safeAbsoluteAvatarUrl(raw);
  }

  const normalized = raw.replace(/^\/+/, "");

  const candidates = normalized.startsWith("avatars/")
    ? [{ bucket: "avatars", path: normalized.slice("avatars/".length) }]
    : normalized.startsWith("safety-gallery/")
      ? [
          {
            bucket: "safety-gallery",
            path: normalized.slice("safety-gallery/".length),
          },
        ]
      : [
          { bucket: "avatars", path: normalized },
          { bucket: "safety-gallery", path: normalized },
        ];

  for (const candidate of candidates) {
    if (!candidate.path) continue;

    try {
      const result = await admin.storage
        .from(candidate.bucket)
        .createSignedUrl(candidate.path, 60 * 30);

      if (result.error) {
        logDatabaseFailure(
          `avatar signing (${candidate.bucket})`,
          result.error,
        );
        continue;
      }

      const url = safeAbsoluteAvatarUrl(clean(result.data?.signedUrl));

      if (url) return url;
    } catch (error) {
      logDatabaseFailure(`avatar signing (${candidate.bucket})`, error);
    }
  }

  return "";
}

async function loadResponderIdentity(
  admin: SupabaseClient,
  params: {
    responderUserId: string;
    contact: ContactRow;
  },
): Promise<ResponderIdentity> {
  const contactEmail = clean(params.contact.email).toLowerCase();
  const contactName =
    clean(params.contact.name) ||
    clean(params.contact.alias) ||
    contactEmail.split("@")[0] ||
    "A Visit contact";

  let displayName = contactName;
  let email = contactEmail;
  let avatarPath = "";
  let verified = false;
  let badgeType = "";
  let badgeStatus = "";

  const [profileResult, userProfileResult, badgeResult] = await Promise.all([
    admin
      .from("profiles")
      .select("first_name,last_name,email,avatar_url,verified")
      .eq("id", params.responderUserId)
      .maybeSingle(),
    admin
      .from("user_profile")
      .select("display_name,first_name,last_name,email,profile_photo_url")
      .eq("user_id", params.responderUserId)
      .maybeSingle(),
    admin
      .from("user_verification_badges")
      .select("badge_type,status,awarded_at,created_at")
      .eq("user_id", params.responderUserId)
      .eq("status", "active")
      .is("removed_at", null)
      .order("awarded_at", { ascending: false })
      .order("created_at", { ascending: false })
      .limit(1)
      .maybeSingle(),
  ]);

  if (profileResult.error) {
    logDatabaseFailure("responder profiles lookup", profileResult.error);
  }

  if (userProfileResult.error) {
    logDatabaseFailure(
      "responder user_profile lookup",
      userProfileResult.error,
    );
  }

  if (badgeResult.error) {
    logDatabaseFailure(
      "responder verification badge lookup",
      badgeResult.error,
    );
  }

  const profile = asObject(profileResult.data);
  const userProfile = asObject(userProfileResult.data);

  const firstName = clean(userProfile.first_name) || clean(profile.first_name);
  const lastName = clean(userProfile.last_name) || clean(profile.last_name);

  displayName =
    clean(userProfile.display_name) ||
    [firstName, lastName].filter(Boolean).join(" ") ||
    displayName;

  email =
    clean(userProfile.email).toLowerCase() ||
    clean(profile.email).toLowerCase() ||
    email;

  avatarPath =
    clean(userProfile.profile_photo_url) || clean(profile.avatar_url);

  verified = profile.verified === true || Boolean(badgeResult.data);

  badgeType = clean(badgeResult.data?.badge_type);
  badgeStatus = clean(badgeResult.data?.status);

  return {
    userId: params.responderUserId,
    displayName,
    email,
    avatarUrl: await signedAvatar(admin, avatarPath),
    verified,
    badgeType,
    badgeStatus,
  };
}

async function loadTiming(
  admin: SupabaseClient,
  visitId: string,
): Promise<TimingRow> {
  const result = await admin
    .from("visit_time_expectations")
    .select("*")
    .eq("visit_id", visitId)
    .maybeSingle();

  if (result.error) {
    logDatabaseFailure("Visit timing lookup", result.error);

    if (backendObjectMissing(result.error)) {
      throw new Error("response_authority_unavailable");
    }

    throw new Error("timing_lookup_failed");
  }

  if (!result.data) {
    throw new Error("timing_not_found");
  }

  return result.data as TimingRow;
}

function validateTiming(params: {
  timing: TimingRow;
  visitId: string;
  ownerUserId: string;
  recipientContactId: string;
}): number {
  const timingVisitId = clean(params.timing.visit_id);
  const timingOwnerId = clean(params.timing.owner_user_id);
  const deadlineVersion = finiteInteger(params.timing.deadline_version) ?? 0;

  if (
    timingVisitId !== params.visitId ||
    timingOwnerId !== params.ownerUserId
  ) {
    throw new Error("timing_subject_mismatch");
  }

  if (deadlineVersion < 1) {
    throw new Error("timing_not_ready");
  }

  const selectedContactIds = asStringArray(params.timing.selected_contact_ids);

  if (!selectedContactIds.includes(params.recipientContactId)) {
    throw new Error("recipient_not_selected");
  }

  const timingStatus = clean(params.timing.status).toLowerCase();

  if (timingStatus && !["active", "extended"].includes(timingStatus)) {
    throw new Error("response_opportunity_closed");
  }

  const expectedEndAt = dateMilliseconds(params.timing.expected_end_at);

  const overdue =
    Boolean(clean(params.timing.first_overdue_at)) ||
    Boolean(clean(params.timing.last_overdue_at)) ||
    (expectedEndAt != null && expectedEndAt <= Date.now());

  if (!overdue) {
    throw new Error("response_opportunity_not_open");
  }

  return deadlineVersion;
}

async function loadSelectedContact(
  admin: SupabaseClient,
  params: {
    ownerUserId: string;
    recipientContactId: string;
    selectedContactIds: string[];
  },
): Promise<ContactRow> {
  if (!params.selectedContactIds.includes(params.recipientContactId)) {
    throw new Error("recipient_not_selected");
  }

  const result = await admin
    .from("emergency_contacts")
    .select(
      "id,user_id,name,alias,email,target_user_id,approval_status,blocked,restricted",
    )
    .eq("id", params.recipientContactId)
    .eq("user_id", params.ownerUserId)
    .eq("approval_status", "approved")
    .maybeSingle();

  if (result.error) {
    logDatabaseFailure("selected contact lookup", result.error);
    throw new Error("recipient_lookup_failed");
  }

  const contact = result.data as ContactRow | null;

  if (!contact || contact.blocked === true || contact.restricted === true) {
    throw new Error("recipient_not_authorized");
  }

  return contact;
}

async function resolveResponderUserId(
  admin: SupabaseClient,
  contact: ContactRow,
): Promise<string> {
  const targetUserId = clean(contact.target_user_id);

  if (isUuid(targetUserId)) {
    return targetUserId;
  }

  const resolved = await resolveStayKnownUserByEmail(
    admin,
    clean(contact.email),
  );

  return isUuid(resolved) ? resolved : "";
}

async function validateConsent(
  admin: SupabaseClient,
  params: {
    consentId: string;
    visitId: string;
    ownerUserId: string;
    recipientContactId: string;
    audience: string;
    signedVersion: string;
    signedExpiry: number;
  },
): Promise<void> {
  if (!isUuid(params.consentId)) {
    throw new Error("consent_required");
  }

  const result = await admin
    .from("visit_map_access_consents")
    .select(
      "id,decision,policy_version,owner_user_id,recipient_contact_id,audience,signed_exp,signed_version",
    )
    .eq("id", params.consentId)
    .eq("visit_id", params.visitId)
    .eq("owner_user_id", params.ownerUserId)
    .eq("recipient_contact_id", params.recipientContactId)
    .eq("decision", "accepted")
    .eq("policy_version", POLICY_VERSION)
    .maybeSingle();

  if (result.error) {
    logDatabaseFailure("LIVE consent lookup", result.error);
    throw new Error("consent_lookup_failed");
  }

  const row = asObject(result.data);

  const matches =
    Boolean(result.data) &&
    clean(row.audience) === params.audience &&
    clean(row.signed_version) === params.signedVersion &&
    Number(row.signed_exp) === params.signedExpiry;

  if (!matches) {
    throw new Error("consent_required");
  }
}

function rpcFailureCode(error: unknown): string {
  const message = clean(asObject(error).message).toLowerCase();

  if (
    message.includes("not attached") ||
    message.includes("cannot respond as their own contact")
  ) {
    return "recipient_not_authorized";
  }

  if (
    message.includes("timing record not found") ||
    message.includes("deadline alert was not found") ||
    message.includes("alert was not found")
  ) {
    return "response_opportunity_closed";
  }

  if (
    message.includes("invalid deadline") ||
    message.includes("invalid visit time response")
  ) {
    return "invalid_response_request";
  }

  return backendObjectMissing(error)
    ? "response_authority_unavailable"
    : "response_record_failed";
}

