export async function POST(req: Request): Promise<NextResponse> {
  try {
    if (!contentTypeIsJson(req)) {
      return jsonResponse(
        {
          ok: false,
          code: "unsupported_content_type",
          error: "Submit this response from the protected StayKnown LIVE page.",
        },
        415,
      );
    }

    if (!requestIsSameOrigin(req)) {
      return jsonResponse(
        {
          ok: false,
          code: "invalid_request_origin",
          error:
            "This response must be submitted from the protected StayKnown LIVE page.",
        },
        403,
      );
    }

    const body = asObject(await req.json().catch(() => ({})));

    if (body.is_practice === true) {
      return jsonResponse(
        {
          ok: false,
          code: "practice_route_required",
          error:
            "Practice Mode responses must use the protected Practice Mode route.",
        },
        409,
      );
    }

    const access = accessFromUnknown(body);
    const verified = verifyLiveAccess(access);

    if (!verified.ok) {
      return jsonResponse(
        {
          ok: false,
          code: "invalid_live_access",
          error: "This signed LIVE Visit access is invalid or expired.",
        },
        401,
      );
    }

    const responseKind = normalizeResponseAction(
      body.response_kind ?? body.action ?? body.action_kind,
    );

    if (!responseKind) {
      throw new Error("invalid_response_request");
    }

    const responseProfile = clean(body.response_profile);

    if (responseProfile !== RESPONSE_PROFILE) {
      throw new Error("invalid_response_profile");
    }

    const submittedOpportunityId = clean(body.response_opportunity_id);

    if (!submittedOpportunityId) {
      throw new Error("invalid_response_opportunity");
    }

    const consentId = clean(body.consent_id);

    const admin = createAdminClient();
    const accessContext = await validateVisitAccess(admin, verified);

    if (!canUseInteractiveLiveActions(verified, accessContext)) {
      throw new Error("recipient_not_authorized");
    }

    if (visitHasEnded(accessContext.visit)) {
      throw new Error("response_opportunity_closed");
    }

    const recipient = accessContext.recipient;

    if (!recipient) {
      throw new Error("recipient_not_authorized");
    }

    const ownerUserId = visitOwnerUserId(accessContext, verified);

    const timing = await loadTiming(admin, verified.sid);

    const deadlineVersion = validateTiming({
      timing,
      visitId: verified.sid,
      ownerUserId,
      recipientContactId: recipient.id,
    });

    const expectedOpportunityId = opportunityId({
      visitId: verified.sid,
      recipientContactId: recipient.id,
      deadlineVersion,
    });

    if (!safeEqualText(submittedOpportunityId, expectedOpportunityId)) {
      throw new Error("invalid_response_opportunity");
    }

    await validateConsent(admin, {
      consentId,
      visitId: verified.sid,
      ownerUserId,
      recipientContactId: recipient.id,
      audience: verified.aud,
      signedVersion: verified.version,
      signedExpiry: verified.expNumber,
    });

    const selectedContactIds = asStringArray(timing.selected_contact_ids);

    const contact = await loadSelectedContact(admin, {
      ownerUserId,
      recipientContactId: recipient.id,
      selectedContactIds,
    });

    const responderUserId = await resolveResponderUserId(admin, contact);

    if (!responderUserId) {
      throw new Error("stayknown_account_required");
    }

    if (responderUserId === ownerUserId) {
      throw new Error("responder_is_owner");
    }

    const responder = await loadResponderIdentity(admin, {
      responderUserId,
      contact,
    });

    const rpc = await recordAuthoritativeResponse(admin, {
      visitId: verified.sid,
      deadlineVersion,
      responder,
      recipientContactId: recipient.id,
      responseKind,
      consentId,
      responseOpportunityId: submittedOpportunityId,
      req,
    });

    const changed = rpc.changed === true;
    const alreadyRecorded =
      rpc.already_recorded === true || (!changed && rpc.changed === false);

    const responseRow = asObject(rpc.response) as RpcResponse;

    const responseId = clean(responseRow.id);
    const respondedAt =
      clean(responseRow.responded_at) ||
      clean(responseRow.updated_at) ||
      new Date().toISOString();

    const copy = responseCopy(responseKind, responder.displayName);

    const delivery: DeliveryProjection = {
      notificationRecorded: false,
      pushDelivered: false,
      pushCode: changed ? "pending" : "unchanged_response",
      timelineRecorded: false,
      deliveryHealthRecorded: false,
      intelligenceRequested: false,
    };

    /*
    The RPC is authoritative. Delivery projections execute only when the
    response actually changed. Repeating the same action remains idempotent and
    does not create another notification, push, timeline event, or intelligence
    trigger.
    */
    if (changed) {
      const notificationId = await upsertOwnerNotification(admin, {
        ownerUserId,
        visitId: verified.sid,
        deadlineVersion,
        responder,
        contactId: recipient.id,
        responseKind,
        responseId,
        copy,
      });

      delivery.notificationRecorded = Boolean(notificationId);

      const push = await sendOwnerPush({
        ownerUserId,
        notificationId,
        visitId: verified.sid,
        deadlineVersion,
        responder,
        contactId: recipient.id,
        responseId,
        responseKind,
        copy,
      });

      delivery.pushDelivered = push.delivered;
      delivery.pushCode = push.code;

      delivery.timelineRecorded = await writeTimelineEvent(admin, {
        ownerUserId,
        visitId: verified.sid,
        deadlineVersion,
        responder,
        contactId: recipient.id,
        responseId,
        responseKind,
        copy,
      });

      delivery.deliveryHealthRecorded = await recordDeliveryHealth(admin, {
        ownerUserId,
        visitId: verified.sid,
        responderUserId,
        responseId,
        responseKind,
        respondedAt,
        notificationRecorded: delivery.notificationRecorded,
        pushDelivered: delivery.pushDelivered,
      });

      delivery.intelligenceRequested = await requestLiveIntelligence({
        ownerUserId,
        visitId: verified.sid,
        responseId,
        responseKind,
        respondedAt,
      });
    }

    const result: RouteSuccess = {
      ok: true,
      session_id: verified.sid,
      changed,
      already_recorded: alreadyRecorded,
      label: alreadyRecorded
        ? "Response already recorded"
        : `${copy.label} recorded`,
      message: alreadyRecorded
        ? "This response was already recorded."
        : copy.confirmation,
      authority: "sk_upsert_visit_time_contact_response",
      response_profile: RESPONSE_PROFILE,
      response: {
        id: responseId || null,
        action: responseKind,
        state: clean(responseRow.status) || "active",
        recorded_at: respondedAt,
        idempotent: alreadyRecorded,
      },
      delivery_health: changed ? deliveryHealth(delivery) : "healthy",
      delivery: {
        notification_recorded: delivery.notificationRecorded,
        push_delivered: delivery.pushDelivered,
        timeline_recorded: delivery.timelineRecorded,
      },
    };

    return jsonResponse(result);
  } catch (error) {
    console.error("[SK_LIVE_RESPONSE] request failed", {
      code: error instanceof Error ? clean(error.message) : "unknown_error",
    });

    const failure = safeFailure(error);

    return jsonResponse(
      {
        ok: false,
        code: failure.code,
        error: failure.message,
      },
      failure.status,
    );
  }
}
